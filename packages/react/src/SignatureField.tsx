const MODE_ORDER: SignatureMode[] = ["draw", "type", "upload", "camera"];

/**
 * Lienzo de trabajo de dibujar y escribir, en píxeles CSS. El alto visible lo
 * controla `--signature-canvas-height`; este es el tamaño del bitmap de la firma,
 * que no depende del tamaño del campo.
 */
const CANVAS_SIZE = { width: 600, height: 200 };

export type SignatureFieldProps = {
  /** Modos ofrecidos, en orden. Por defecto los cuatro. */
  modes?: SignatureMode[];
  /** Pestaña inicial. Por defecto, el primer mode availableMode. */
  initialMode?: SignatureMode;
  /** Nombre a escribir. Sin name, el mode `escribir` no se ofrece. */
  name?: string;
  /** Signature ya elegida por el padre (mode controlado). */
  value?: Signature | null;
  onSignature?: (signature: Signature | null) => void;
  onRejection?: (reason: RejectionReason, message: string) => void;
  verifier?: Verifier;
  maxWidth?: number;
  locale?: Locale;
  /**
   * Fuerza el esquema del componente. Sin esto sigue la preferencia del sistema,
   * y en cualquier caso pinta su propia superficie: el contraste no depende de
   * la página que lo hospeda.
   */
  theme?: "light" | "dark";
  /**
   * Tope de peso del archivo subido, en bytes. Por defecto 5 MB: por encima, el
   * navegador sufre decodificando y la foto de una firma no lo necesita.
   */
  maxBytes?: number;
  /**
   * Grosor, suavizado y color del trazo dibujado. Los valores del paquete son un
   * buen punto de partida; esto existe para quien quiere un trazo más fino o más
   * grueso sin reimplementar el modo.
   */
  stroke?: StrokeOptions;
  /**
   * Tamaño del campo: cambia el lienzo y el aire, nunca los objetivos táctiles,
   * que siguen en 44px como mínimo.
   */
  size?: "sm" | "md" | "lg";
  /** Cursivas ofrecidas en el modo escribir. Por defecto, las cuatro del paquete. */
  fonts?: TypeFont[];
  /** Cursiva elegida (modo controlado). */
  font?: TypeFont;
  onFontChange?: (font: TypeFont) => void;
  label?: string;
  className?: string;
  /**
   * Estilos en línea del contenedor. Es la vía corta para sobrescribir tokens
   * (`--signature-*`) sin crear una hoja de estilos propia.
   */
  style?: React.CSSProperties;
  /** Puertos inyectables: pruebas sin canvas real. */
  encoder?: PngEncoder;
  measurer?: TextMeasurer;
  rasterizer?: TextRasterizer;
};

export type SignatureFieldHandle = {
  clear: () => void;
  confirm: () => void;
  openMode: (mode: SignatureMode) => void;
  /** Quita el último trazo (solo tiene efecto en el modo dibujar). */
  undo: () => void;
};

/**
 * Which modes can honestly be offered: `type` needs a name and `camera` needs a
 * camera. Hiding an impossible mode beats rendering a button that fails.
 */
export function availableModes(options: {
  // `| undefined` explícito: quien llama pasa props opcionales tal cual, y con
  // `exactOptionalPropertyTypes` eso no es lo mismo que una clave ausente.
  modes?: SignatureMode[] | undefined;
  name?: string | undefined;
  hasCamera: boolean;
}): SignatureMode[] {
  const requested = options.modes?.length ? options.modes : MODE_ORDER;
  const withName = Boolean(options.name?.trim());
  return requested.filter((mode) => {
    if (mode === "type") return withName;
    if (mode === "camera") return options.hasCamera;
    return true;
  });
}

function hasCameraSupport(): boolean {
  return Boolean(
    (globalThis as { navigator?: Navigator }).navigator?.mediaDevices
  );
}

/** Decodifica un file del usuario a RGBA. Sin canvas, no hay signature. */
async function readBitmap(file: File): Promise<Bitmap> {
  const bitmap = await createImageBitmap(file);
  const canvas = document.createElement("canvas");
  canvas.width = bitmap.width;
  canvas.height = bitmap.height;
  const ctx = canvas.getContext("2d");
  if (!ctx) throw new Error("sin contexto 2D");
  ctx.drawImage(bitmap, 0, 0);
  const data = ctx.getImageData(0, 0, bitmap.width, bitmap.height);
  return { data: data.data, width: bitmap.width, height: bitmap.height };
}

export const SignatureField = forwardRef<SignatureFieldHandle, SignatureFieldProps>(
  function SignatureField(props, ref) {
    const {
      modes,
      initialMode,
      name,
      value,
      onSignature,
      onRejection,
      verifier,
      maxWidth = 900,
      label,
      locale = "en",
      maxBytes = 5 * 1024 * 1024,
      size = "md",
      stroke,
      theme,
      fonts = [...TYPE_FONTS],
      font,
      onFontChange,
      className,
      style,
      encoder,
      measurer,
      rasterizer,
    } = props;

    const available = useMemo(
      () => availableModes({ modes, name, hasCamera: hasCameraSupport() }),
      [modes, name]
    );
    const [mode, setMode] = useState<SignatureMode>(() => {
      const initial = initialMode ?? available[0] ?? "draw";
      return available.includes(initial) ? initial : (available[0] ?? "draw");
    });
    // Los puntos se guardan por trazo, no en una lista plana: así «deshacer»
    // quita el último trazo entero en vez de un punto suelto.
    const [strokes, setStrokes] = useState<StrokePoint[][]>([]);
    const points = useMemo(() => strokes.flat(), [strokes]);
    const [file, setFile] = useState<File | null>(null);
    const [signature, setSignature] = useState<Signature | null>(value ?? null);
    const [error, setError] = useState<string | null>(null);
    const [busy, setBusy] = useState(false);
    // La cursiva elegida: controlada por el padre si pasa `font`, si no interna.
    const [chosenFont, setChosenFont] = useState<TypeFont>(font ?? fonts[0] ?? "Caveat");
    const activeFont = font ?? chosenFont;

    const drawing = useRef(false);
    const canvasRef = useRef<HTMLCanvasElement | null>(null);
    const tabsRef = useRef<Record<string, HTMLButtonElement | null>>({});
    const baseId = useId();

    const effectiveEncoder = useMemo(
      () => encoder ?? createCanvasPngEncoder(),
      [encoder]
    );
    const effectiveMeasurer = useMemo(
      () => measurer ?? createCanvasTextMeasurer(),
      [measurer]
    );
    const effectiveRasterizer = useMemo(
      () => rasterizer ?? createCanvasTextRasterizer(),
      [rasterizer]
    );

    const texts = FIELD_TEXT[locale] ?? FIELD_TEXT.en;
    const tabLabels = TAB_LABELS[locale] ?? TAB_LABELS.en;
    const visibleSignature = value !== undefined ? value : signature;

    // `exactOptionalPropertyTypes`: la clave `verificador` solo aparece cuando
    // hay un verificador de verdad, así que "no verificar" tiene una única
    // representación.
    const coreOptions = useMemo<SignatureOptions>(() => {
      // `locale` viaja al core: si no, la alerta de rechazo saldría en inglés
      // con la interfaz en español.
      const base: SignatureOptions = { maxWidth, locale };
      return verifier ? { ...base, verifier } : base;
    }, [locale, maxWidth, verifier]);

    // Vista previa de lo que se va a guardar: antes solo había un texto de
    // "lista", así que la persona firmaba a ciegas. El object URL se revoca al
    // cambiar, igual que en el playground.
    // Vista previa del archivo elegido: antes solo se veía el nombre del input
    // nativo, así que se confirmaba a ciegas también aquí.
    const fileUrl = useMemo(
      () => (file ? URL.createObjectURL(file) : null),
      [file]
    );
    useEffect(() => {
      if (!fileUrl) return;
      return () => URL.revokeObjectURL(fileUrl);
    }, [fileUrl]);

    const previewUrl = useMemo(
      () => (visibleSignature ? URL.createObjectURL(toPngBlob(visibleSignature)) : null),
      [visibleSignature]
    );
    useEffect(() => {
      if (!previewUrl) return;
      return () => URL.revokeObjectURL(previewUrl);
    }, [previewUrl]);

    // El lienzo de dibujar se pinta con el mismo rasterizador puro que usa el
    // core: lo que se ve es exactamente lo que se va a guardar.
    useEffect(() => {
      const canvas = canvasRef.current;
      if (!canvas) return;
      const ctx = canvas.getContext("2d");
      if (!ctx) return;
      // El preview usa exactamente las mismas opciones que la firma final.
      const bitmap = rasterizeStroke(points, CANVAS_SIZE, stroke ?? {});
      const image = ctx.createImageData(bitmap.width, bitmap.height);
      image.data.set(bitmap.data);
      ctx.putImageData(image, 0, 0);
    }, [points, mode, stroke]);

    const clear = useCallback(() => {
      setStrokes([]);
      setFile(null);
      setError(null);
      // En controlado el estado interno no manda, pero el padre sí tiene que
      // enterarse de que la persona limpió el campo: si no, nunca puede soltar
      // su `value` y el componente queda imposible de reiniciar.
      if (value === undefined) setSignature(null);
      onSignature?.(null);
    }, [onSignature, value]);

    const undo = useCallback(() => {
      setStrokes((previas) => previas.slice(0, -1));
    }, []);

    const confirm = useCallback(async () => {
      setError(null);
      setBusy(true);
      try {
        let result;
        if (mode === "draw") {
          result = await sign(
            // `exactOptionalPropertyTypes`: la clave solo existe si hay trazo
            // propio que pasar.
            { mode: "draw", points, canvas: CANVAS_SIZE, ...(stroke ? { stroke } : {}) },
            effectiveEncoder,
            coreOptions
          );
        } else if (mode === "type") {
          // Se carga la cursiva elegida antes de medir: si se mide con la de
          // reserva, el nombre se sale de la caja.
          await loadFont(activeFont, 72);
          result = await sign(
            {
              mode: "type",
              text: (name ?? "").trim(),
              canvas: CANVAS_SIZE,
              measurer: effectiveMeasurer,
              rasterizer: effectiveRasterizer,
              font: activeFont,
            },
            effectiveEncoder,
            coreOptions
          );
        } else {
          if (!file) {
            setError(texts.chooseFile!);
            return;
          }
          // Formato y peso se comprueban ANTES de decodificar: decodificar una
          // foto de 40 MB para luego rechazarla es trabajo tirado, y en un móvil
          // se nota. `detectFormat` mira los magic bytes, no la extensión.
          if (file.size > maxBytes) {
            const message = rejectionMessage("too_heavy", locale);
            setError(message);
            onRejection?.("too_heavy", message);
            return;
          }
          const cabecera = new Uint8Array(
            await file.slice(0, 8).arrayBuffer()
          );
          if (detectFormat(cabecera) === null) {
            const message = rejectionMessage("unsupported_format", locale);
            setError(message);
            onRejection?.("unsupported_format", message);
            return;
          }

          const image = await readBitmap(file).catch(() => null);
          if (!image) {
            const message = rejectionMessage("unreadable", locale);
            setError(message);
            onRejection?.("unreadable", message);
            return;
          }
          result = await sign(
            { mode: mode === "camera" ? "camera" : "upload", image },
            effectiveEncoder,
            coreOptions
          );
        }

        if (result.ok) {
          if (value === undefined) setSignature(result.signature);
          onSignature?.(result.signature);
        } else {
          setError(result.message);
          onRejection?.(result.reason, result.message);
        }
      } catch {
        // Un fallo del navegador (canvas bloqueado) no puede dejar el botón
        // girando para siempre.
        setError(rejectionMessage("unreadable", locale));
        onRejection?.("unreadable", rejectionMessage("unreadable", locale));
      } finally {
        setBusy(false);
      }
    }, [
      file,
      effectiveEncoder,
      effectiveMeasurer,
      mode,
      name,
      onSignature,
      onRejection,
      coreOptions,
      points,
      effectiveRasterizer,
      value,
      // Sin esto el callback se queda con la cursiva inicial: el test de
      // elección de fuente lo detectó.
      activeFont,
    ]);

    useImperativeHandle(
      ref,
      () => ({
        clear,
        confirm: () => void confirm(),
        openMode: setMode,
        undo,
      }),
      [clear, confirm, undo]
    );

    const onKeyDown = useCallback(
      (event: React.KeyboardEvent<HTMLButtonElement>, current: SignatureMode) => {
        const indice = available.indexOf(current);
        let destino: number | null = null;
        if (event.key === "ArrowRight") destino = (indice + 1) % available.length;
        else if (event.key === "ArrowLeft")
          destino = (indice - 1 + available.length) % available.length;
        else if (event.key === "Home") destino = 0;
        else if (event.key === "End") destino = available.length - 1;
        if (destino === null) return;
        event.preventDefault();
        const next = available[destino];
        if (!next) return;
        setMode(next);
        tabsRef.current[next]?.focus();
      },
      [available]
    );

    const point = useCallback(
      (event: React.PointerEvent<HTMLCanvasElement>): StrokePoint | null => {
        const canvas = canvasRef.current;
        if (!canvas) return null;
        const bounds = canvas.getBoundingClientRect();
        if (bounds.width === 0 || bounds.height === 0) return null;
        return {
          x: ((event.clientX - bounds.left) * CANVAS_SIZE.width) / bounds.width,
          y: ((event.clientY - bounds.top) * CANVAS_SIZE.height) / bounds.height,
          t: event.timeStamp,
        };
      },
      []
    );

    return (
      <div
        className={className ? `signature ${className}` : "signature"}
        data-theme={theme}
        data-size={size}
        style={style}
      >
        <div className="signature__tabs" role="tablist" aria-label={label ?? (locale === "es" ? "Firma" : "Signature")}>
          {available.map((availableMode) => {
            const active = availableMode === mode;
            return (
              <button
                key={availableMode}
                ref={(el) => {
                  tabsRef.current[availableMode] = el;
                }}
                type="button"
                role="tab"
                id={`${baseId}-tab-${availableMode}`}
                aria-selected={active}
                aria-controls={`${baseId}-panel`}
                tabIndex={active ? 0 : -1}
                className={active ? "signature__tab signature__tab--active" : "signature__tab"}
                onClick={() => setMode(availableMode)}
                onKeyDown={(event) => onKeyDown(event, availableMode)}
              >
                {tabLabels[availableMode]}
              </button>
            );
          })}
        </div>

        <div
          className="signature__panel"
          role="tabpanel"
          id={`${baseId}-panel`}
          aria-labelledby={`${baseId}-tab-${mode}`}
        >
          {mode === "draw" ? (
            <div className="signature__canvas-wrap">
              {strokes.length === 0 ? (
                // Guía visual: un lienzo en blanco no dice qué hacer. Es
                // aria-hidden porque el canvas ya tiene su nombre accesible.
                <p className="signature__hint" aria-hidden="true">
                  {texts.hint}
                </p>
              ) : null}
            <canvas
              ref={canvasRef}
              className="signature__canvas"
              width={CANVAS_SIZE.width}
              height={CANVAS_SIZE.height}
              aria-label={texts.canvas}
              onPointerDown={(event) => {
                drawing.current = true;
                event.currentTarget.setPointerCapture(event.pointerId);
                const p = point(event);
                if (p) setStrokes((previos) => [...previos, [p]]);
              }}
              onPointerMove={(event) => {
                if (!drawing.current) return;
                const p = point(event);
                if (!p) return;
                setStrokes((previos) => {
                  const ultimo = previos.at(-1);
                  if (!ultimo) return [[p]];
                  return [...previos.slice(0, -1), [...ultimo, p]];
                });
              }}
              onPointerUp={() => {
                drawing.current = false;
              }}
              onPointerCancel={() => {
                drawing.current = false;
              }}
            />
            </div>
          ) : null}

          {mode === "type" ? (
            <div className="signature__fonts">
              {fonts.length > 1 ? (
                <div
                  className="signature__font-options"
                  role="radiogroup"
                  aria-label={texts.fontLabel}
                >
                  {fonts.map((option) => (
                    <label
                      key={option}
                      className={
                        option === activeFont
                          ? "signature__font signature__font--active"
                          : "signature__font"
                      }
                      style={{ fontFamily: fontFamily(option) }}
                    >
                      <input
                        type="radio"
                        name={`${baseId}-font`}
                        value={option}
                        checked={option === activeFont}
                        onChange={() => {
                          if (font === undefined) setChosenFont(option);
                          onFontChange?.(option);
                        }}
                      />
                      {option}
                    </label>
                  ))}
                </div>
              ) : null}
              <p className="signature__preview" aria-live="polite">
                {name?.trim()
                  ? `${texts.typeHint}: ${name.trim()}`
                  : texts.typeEmpty}
              </p>
            </div>
          ) : null}

          {mode === "upload" || mode === "camera" ? (
            <label className="signature__file">
              <span>
                {mode === "camera" ? texts.camera : texts.upload}
              </span>
              <input
                type="file"
                accept="image/png,image/jpeg"
                {...(mode === "camera" ? { capture: "environment" as const } : {})}
                onChange={(event) => {
                  setFile(event.target.files?.[0] ?? null);
                  setError(null);
                }}
              />
            </label>
          ) : null}

          {fileUrl ? (
            <img
              src={fileUrl}
              alt={texts.filePreviewAlt}
              className="signature__result-image"
            />
          ) : null}

          <div className="signature__actions">
            {mode === "draw" ? (
              <button
                type="button"
                className="signature__button"
                onClick={undo}
                disabled={strokes.length === 0}
              >
                {texts.undo}
              </button>
            ) : null}
            <button type="button" className="signature__button" onClick={clear}>
              {texts.clear}
            </button>
            <button
              type="button"
              className="signature__button signature__button--primary"
              onClick={() => void confirm()}
              disabled={busy}
            >
              {busy ? texts.busy : texts.confirm}
            </button>
          </div>

          {error ? (
            <p className="signature__error" role="alert">
              {error}
            </p>
          ) : null}

          {previewUrl ? (
            <div className="signature__result">
              <img
                src={previewUrl}
                alt={texts.previewAlt}
                className="signature__result-image"
              />
              <p className="signature__status">
                {visibleSignature!.width}×{visibleSignature!.height} px ·{" "}
                {Math.round(visibleSignature!.png.byteLength / 1024)} KB
              </p>
            </div>
          ) : null}
          {/* La región viva se mantiene aunque haya vista previa: quien usa un
              lector de pantalla necesita que se le anuncie el resultado, no solo
              ver una imagen. */}
          <p className="signature__status" aria-live="polite">
            {visibleSignature ? texts.ready : ""}
          </p>
        </div>
      </div>
    );
  }
);
